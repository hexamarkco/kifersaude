async (page) => {
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const results = [];
  const requests = [];
  let responseMode = 'error';
  let release;
  await page.route('**/functions/v1/public-lead-submit', async route => {
    requests.push(route.request().postDataJSON());
    await new Promise(resolve => { release = resolve; });
    await route.fulfill({ status: responseMode === 'error' ? 500 : 200, contentType: 'application/json', body: responseMode === 'error' ? '{"error":"Falha simulada"}' : '{"success":true}', headers: { 'Access-Control-Allow-Origin': '*' } });
  });
  await page.route('**/servicodados.ibge.gov.br/**', route => route.fulfill({ contentType: 'application/json', body: '[{"nome":"Rio de Janeiro"},{"nome":"Niterói"}]', headers: { 'Access-Control-Allow-Origin': '*' } }));
  await page.addInitScript(() => { window.__homeOpenedUrls = []; window.open = (url) => { window.__homeOpenedUrls.push(String(url)); return null; }; });
  await page.goto('http://127.0.0.1:5175/');
  await page.locator('#home-title').waitFor();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Abrir menu' }).click();
  const dialog = page.getByRole('dialog');
  assert(await dialog.isVisible(), 'Menu mobile não abriu');
  await dialog.screenshot({ path: 'output/playwright/home-redesign/mobile-menu.png' });
  await page.keyboard.press('Escape');
  assert(!await dialog.count(), 'Escape não fechou menu');
  assert(await page.getByRole('button', { name: 'Abrir menu' }).evaluate(e => e === document.activeElement), 'Foco não retornou ao menu');
  await page.getByRole('button', { name: 'Abrir menu' }).click();
  await page.getByRole('navigation', { name: 'Navegação móvel' }).getByRole('link', { name: 'Dúvidas' }).click();
  assert(!await dialog.count(), 'Navegação não fechou menu');
  assert(new URL(page.url()).hash === '#faq', 'Âncora do menu incorreta');
  results.push('Menu: abrir, Escape, retorno de foco, navegação e fechamento');

  const pf = page.locator('input[name="audience-profile"][value="PF"]');
  await pf.focus();
  await page.keyboard.press('ArrowDown');
  assert(await page.locator('#audience-panel').getAttribute('aria-labelledby') === 'audience-label-MEI', 'Seleção de perfil por teclado não atualizou painel');
  assert(await page.locator('#audience-panel img').getAttribute('src') === '/images/home/work.png', 'Foto do perfil MEI incorreta');
  await page.locator('#audience-panel').getByRole('button').click();
  assert(await page.locator('input[name="quote-contract-type"][value="MEI"]').isChecked(), 'CTA não levou perfil ao formulário');
  assert(new URL(page.url()).hash === '#cotacao', 'CTA não navegou à cotação');
  results.push('Perfis: troca por teclado, conteúdo/foto e CTA sincronizado com formulário');
  const faq = page.locator('#faq-trigger-0');
  await faq.focus();
  await page.keyboard.press('Enter');
  assert(await faq.getAttribute('aria-expanded') === 'true', 'FAQ não expandiu com Enter');
  assert(await page.locator('#faq-answer-0').isVisible(), 'Resposta do FAQ não está visível');
  await page.keyboard.press('Space');
  assert(await faq.getAttribute('aria-expanded') === 'false', 'FAQ não fechou com espaço');
  results.push('FAQ: Enter e espaço, aria-expanded e resposta visível/oculta');

  const form = page.locator('#cotacao form');
  await form.getByRole('button', { name: 'Quero receber minha cotação' }).click();
  assert(requests.length === 0, 'Formulário vazio enviou requisição');
  await page.locator('#quote-lives').fill('1');
  await page.locator('#quote-age').fill('35');
  await page.locator('#quote-city').fill('Rio');
  await page.locator('#quote-city').press('ArrowDown');
  await page.locator('#quote-city').press('Enter');
  assert(await page.locator('#quote-city').inputValue() === 'Rio de Janeiro', 'Autocompletar de cidade não selecionou com teclado');
  await page.locator('#quote-name').fill('AB');
  await page.locator('#quote-phone').fill('21999999999');
  await form.getByRole('button', { name: 'Quero receber minha cotação' }).click();
  assert(requests.length === 0, 'Nome curto enviou requisição');
  assert(await page.locator('#quote-name').getAttribute('aria-invalid') === 'true', 'Nome inválido sem associação acessível de erro');
  await page.locator('#quote-name').fill('Contato de teste');
  await page.locator('#quote-lives').fill('2');
  await page.locator('#quote-range-0').fill('1');
  await form.getByRole('button', { name: 'Quero receber minha cotação' }).click();
  assert(requests.length === 0, 'Soma de faixas inconsistente enviou requisição');
  await page.locator('#cotacao').screenshot({ path: 'output/playwright/home-redesign/mobile-form-validation.png' });
  await page.locator('#quote-range-3').fill('1');
  await form.getByRole('button', { name: 'Quero receber minha cotação' }).click();
  await page.waitForFunction(() => document.querySelector('#cotacao button[type="submit"]').disabled);
  assert(await form.getAttribute('aria-busy') === 'true', 'Formulário sem estado de envio');
  assert(await page.locator('#quote-name').isDisabled(), 'Campos não bloqueados durante envio');
  await page.locator('#cotacao').screenshot({ path: 'output/playwright/home-redesign/mobile-form-loading.png' });
  assert(requests.length === 1, 'Quantidade incorreta de requisições no envio');
  release();
  await form.getByRole('alert').filter({ hasText: 'Não foi possível enviar' }).waitFor();
  assert(await page.locator('#quote-name').inputValue() === 'Contato de teste', 'Erro apagou os dados');
  assert(await page.evaluate(() => window.__homeOpenedUrls.length) === 0, 'WhatsApp aberto antes de confirmação');
  await page.locator('#cotacao').screenshot({ path: 'output/playwright/home-redesign/mobile-form-error.png' });
  responseMode = 'success';
  await form.getByRole('button', { name: 'Quero receber minha cotação' }).click();
  await page.waitForFunction(() => document.querySelector('#cotacao button[type="submit"]').disabled);
  release();
  await form.getByRole('status').filter({ hasText: 'Pedido de cotação enviado' }).waitFor();
  const opened = await page.evaluate(() => window.__homeOpenedUrls);
  assert(opened.length === 1 && opened[0].startsWith('https://wa.me/5521979302389?text='), 'Redirecionamento não usou WhatsApp oficial');
  assert(await page.locator('#quote-name').inputValue() === '', 'Sucesso não limpou campos');
  assert(requests.length === 2, 'Envios duplicados ou pedidos inesperados');
  assert(requests[1].phone === '21999999999' && requests[1].contractType === 'MEI' && requests[1].totalLives === 2, 'Payload de captação mudou');
  assert(requests[1].ageSummary.counts['00-18'] === 1 && requests[1].ageSummary.counts['29-33'] === 1 && Object.keys(requests[1].ageSummary.counts).length === 10, 'Faixas etárias do payload incorretas');
  assert(requests[1].website === '', 'Honeypot ausente do contrato');
  await page.locator('#cotacao').screenshot({ path: 'output/playwright/home-redesign/mobile-form-success.png' });
  results.push('Formulário: obrigatório, nome, soma de idades, autocompletar, loading/bloqueio, erro preserva dados, sucesso, payload fechado e WhatsApp só após confirmação');
  assert(await page.locator('a[href*="wa.me"]').evaluateAll(links => links.every(link => link.href.startsWith('https://wa.me/5521979302389'))), 'Link de WhatsApp não oficial');
  results.push('Links de WhatsApp oficiais; todas as escritas interceptadas localmente; nenhum lead real enviado');
  await page.unroute('**/functions/v1/public-lead-submit');
  await page.reload();
  await page.locator('#home-title').waitFor();
  return { results, mockedSubmissions: requests, externalWindowsPrevented: opened.length };
}
