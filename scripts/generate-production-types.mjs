import { readFile, writeFile } from 'node:fs/promises';
import { createProductionTestDatabase } from './lib/production-test-database.mjs';

// Generate the additive schema from real Postgres catalogs without touching production.
// database.generated.ts continues to describe the linked deployment until remote rollout.
const db = await createProductionTestDatabase();
try {
  const typeMap = { uuid:'string', text:'string', boolean:'boolean', bigint:'number', integer:'number', date:'string', 'timestamp with time zone':'string', jsonb:'Json' };
  const { rows } = await db.query(`SELECT table_name,column_name,data_type,is_nullable,column_default,is_identity FROM information_schema.columns WHERE table_schema='public' AND table_name IN ('production_operators','production_settings','production_activities') ORDER BY table_name,ordinal_position`);
  let output = '// Generated by scripts/generate-production-types.mjs. Do not edit.\nimport type { Json } from \'./database.generated\';\n\nexport type ProductionTables = {\n';
  for (const table of [...new Set(rows.map((row) => row.table_name))]) {
    output += `  ${table}: {\n`;
    for (const shape of ['Row','Insert','Update']) {
      output += `    ${shape}: {\n`;
      for (const row of rows.filter((row) => row.table_name===table)) {
        const nullable = row.is_nullable==='YES';
        const optional = shape==='Update' || (shape==='Insert' && (nullable || row.column_default || row.is_identity==='YES'));
        output += `      ${row.column_name}${optional?'?':''}: ${typeMap[row.data_type] ?? 'never'}${nullable?' | null':''};\n`;
      }
      output += '    };\n';
    }
    output += '    Relationships: [];\n  };\n';
  }
  output += '};\nexport type ProductionFunctions = {\n';
  const functions = await db.query(`SELECT p.proname,p.proargnames,p.proargtypes::oid[] AS types,p.pronargdefaults,p.prorettype::regtype::text AS return_type FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='public' AND p.proname IN ('team_production_report','activate_team_production','production_message_attribution','production_scheduled_operator') ORDER BY p.proname`);
  for (const fn of functions.rows) {
    const types = fn.types ?? [];
    const args = [];
    for (let index=0;index<types.length;index++) {
      const { rows: [pgType] } = await db.query('SELECT format_type($1::oid,NULL) AS type',[types[index]]);
      args.push(`${fn.proargnames[index]}${index >= types.length-fn.pronargdefaults?'?':''}: ${typeMap[pgType.type]??'never'}`);
    }
    output += `  ${fn.proname}: { Args: ${args.length?`{ ${args.join('; ')} }`:'Record<PropertyKey, never>'}; Returns: ${typeMap[fn.return_type]??(fn.return_type==='void'?'undefined':'never')} };\n`;
  }
  output += '};\n';
  const columns = await db.query("SELECT column_name FROM information_schema.columns WHERE table_schema='public' AND table_name='contracts' AND column_name='sale_operator_user_id'");
  output += `export type ContractProductionFields = { ${columns.rows.map((row)=>`${row.column_name}?: string | null`).join('; ')} };\n`;
  const target = new URL('../src/infrastructure/supabase/production.generated.ts',import.meta.url);
  if (process.argv.includes('--check')) {
    if (await readFile(target,'utf8') !== output) throw new Error('Execute npm run types:production.');
  } else await writeFile(target,output);
  process.stdout.write('Tipos incrementais de produção validados a partir da migration local.\n');
} finally { await db.close(); }
